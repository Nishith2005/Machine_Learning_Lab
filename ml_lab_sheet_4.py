def calculate_mean(data, axis=None):
    """
    Calculate mean of data.
    """

    data = np.asarray(
        data,
        dtype=float
    )

    return np.mean(
        data,
        axis=axis
    )


def calculate_variance(data, axis=None):
    """
    Calculate population variance.
    """

    data = np.asarray(
        data,
        dtype=float
    )

    mean = np.mean(
        data,
        axis=axis,
        keepdims=True
    )

    return np.mean(
        (data - mean) ** 2,
        axis=axis
    )


def calculate_standard_deviation(
    data,
    axis=None
):
    """
    Calculate population standard deviation.
    """

    return np.sqrt(
        calculate_variance(
            data,
            axis
        )
    )


