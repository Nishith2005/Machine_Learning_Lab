def dot_product(vector_a, vector_b):
    """
    Calculate dot product of two vectors.
    """

    vector_a = np.asarray(
        vector_a,
        dtype=float
    )

    vector_b = np.asarray(
        vector_b,
        dtype=float
    )

    return np.sum(
        vector_a * vector_b
    )


def euclidean_norm(vector):
    """
    Calculate Euclidean norm of a vector.
    """

    vector = np.asarray(
        vector,
        dtype=float
    )

    return np.sqrt(
        np.sum(vector ** 2)
    )


