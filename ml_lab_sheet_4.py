def calculate_inertia(
    data,
    labels,
    centroids
):
    """
    Calculate within-cluster sum of squared distances.
    """

    inertia = 0.0

    for cluster in range(
        len(centroids)
    ):

        cluster_points = data[
            labels == cluster
        ]

        if len(cluster_points) > 0:

            inertia += np.sum(
                (
                    cluster_points
                    -
                    centroids[cluster]
                ) ** 2
            )

    return inertia


