import pandas as pd
import numpy as np

file = "Lab Session Data (1).xlsx"
df = pd.read_excel(file, sheet_name="thyroid0387_UCI")
imputed = df.copy()
for col in imputed.columns:
    if imputed[col].dtype == object:
        imputed[col].fillna(imputed[col].mode()[0], inplace=True)
    else:
        Q1 = imputed[col].quantile(0.25)
        Q3 = imputed[col].quantile(0.75)
        IQR = Q3-Q1
        lower = Q1-1.5*IQR
        upper = Q3+1.5*IQR
        outliers = imputed[(imputed[col]<lower) | (imputed[col]>upper)]
        if len(outliers)==0:
            imputed[col].fillna(imputed[col].mean(), inplace=True)
        else:
            imputed[col].fillna(imputed[col].median(), inplace=True)
print(imputed.isnull().sum())
