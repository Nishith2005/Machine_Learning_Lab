import pandas as pd
import numpy as np
import seaborn as sns
import matplotlib.pyplot as plt
from sklearn.preprocessing import LabelEncoder

file = "Lab Session Data (1).xlsx"

df = pd.read_excel(file, sheet_name="thyroid0387_UCI")
encoded = df.copy()
le = LabelEncoder()

for col in encoded.columns:
    if encoded[col].dtype == object:
        encoded[col] = le.fit_transform(encoded[col].astype(str))

encoded = encoded.fillna(0)
binary = (encoded > 0).astype(int)

n = 20

JC_matrix = np.zeros((n,n))
SMC_matrix = np.zeros((n,n))
COS_matrix = np.zeros((n,n))

for i in range(n):
    for j in range(n):
        a = binary.iloc[i].values
        b = binary.iloc[j].values
        f11 = np.sum((a==1)&(b==1))
        f10 = np.sum((a==1)&(b==0))
        f01 = np.sum((a==0)&(b==1))
        f00 = np.sum((a==0)&(b==0))

        if (f11+f10+f01)==0:
            JC = 0
        else:
            JC = f11/(f11+f10+f01)

        SMC = (f11+f00)/(f11+f10+f01+f00)

        JC_matrix[i,j]=JC
        SMC_matrix[i,j]=SMC

        x = encoded.iloc[i].values.astype(float)
        y = encoded.iloc[j].values.astype(float)

        COS_matrix[i,j] = np.dot(x,y)/(np.linalg.norm(x)*np.linalg.norm(y))

# Jaccard Heatmap
plt.figure(figsize=(8,6))
sns.heatmap(JC_matrix, annot=True, cmap="Blues")
plt.title("Jaccard Similarity")
plt.show()

# SMC Heatmap
plt.figure(figsize=(8,6))
sns.heatmap(SMC_matrix, annot=True, cmap="Greens")
plt.title("Simple Matching Coefficient")
plt.show()

# Cosine Heatmap
plt.figure(figsize=(8,6))
sns.heatmap(COS_matrix, annot=True, cmap="Reds")
plt.title("Cosine Similarity")
plt.show()

